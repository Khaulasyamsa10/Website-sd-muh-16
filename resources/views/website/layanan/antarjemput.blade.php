@if($antarJemput?->pamflet_gambar)

    <script>

        function openAntarPamphlet()
        {
            const modal =
                document.getElementById(
                    'antar-pamphlet-modal'
                );

            if (!modal) {
                return;
            }

            modal.classList.add('show');

            document.body.classList.add(
                'antar-modal-open'
            );
        }


        function closeAntarPamphlet()
        {
            const modal =
                document.getElementById(
                    'antar-pamphlet-modal'
                );

            if (!modal) {
                return;
            }

            modal.classList.remove('show');

            document.body.classList.remove(
                'antar-modal-open'
            );
        }


        document.addEventListener(
            'keydown',
            function(event)
            {
                if (event.key === 'Escape') {

                    closeAntarPamphlet();

                }
            }
        );

    </script>

